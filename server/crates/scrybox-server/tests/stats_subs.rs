async fn get_json(r: &Router, path: &str) -> (StatusCode, HeaderMap, Value) {
    let (s, h, b) = request(r, "GET", path, &auth()).await;
    (s, h, serde_json::from_slice(&b).unwrap())
}

/// Replace the response's random-by-design asOf (fresh-stamped per request,
/// hit or miss, exactly like Node's cached() onHit) with the oracle
/// placeholder so the rest of the body can be byte-compared.
fn split_asof(body: &str) -> (String, String) {
    const KEY: &str = "\"asOf\":\"";
    let i = body.find(KEY).expect("asOf key present");
    let rest = &body[i + KEY.len()..];
    let j = rest.find('"').expect("asOf value closed");
    (
        format!("{}\"asOf\":\"__ASOF__{}", &body[..i], &rest[j..]),
        rest[..j].to_string(),
    )
}

/// new Date().toISOString() shape, checked without a regex dependency.
fn is_iso_ms(s: &str) -> bool {
    let b = s.as_bytes();
    let digit = |i: usize| b[i].is_ascii_digit();
    b.len() == 24
        && [0, 1, 2, 3, 5, 6, 8, 9, 11, 12, 14, 15, 17, 18, 20, 21, 22].iter().all(|&i| digit(i))
        && b[4] == b'-' && b[7] == b'-' && b[10] == b'T'
        && b[13] == b':' && b[16] == b':' && b[19] == b'.'
        && b[23] == b'Z'
}

