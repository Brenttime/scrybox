#[tokio::test]
async fn miss_hit_304_replay_and_byte_stability() {
    let dir = tempfile::tempdir().unwrap();
    let upstream = spawn_fake_node().await;
    let r = router_for(seeded_stats_db(dir.path(), "cache.db"), &["stats_subs"], &format!("http://{upstream}"));

    let (s1, h1, b1) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(s1, StatusCode::OK);
    assert_eq!(h1["x-stats-cache"], "miss");
    let (s2, h2, b2) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(s2, StatusCode::OK);
    assert_eq!(h2["x-stats-cache"], "hit", "second call within TTL serves the stored body");
    assert_eq!(b1, b2, "cached replay is byte-stable");
    assert_eq!(h1[header::ETAG], h2[header::ETAG]);

    let etag = h2[header::ETAG].to_str().unwrap().to_string();
    let (s3, h3, b3) = request(
        &r, "GET", "/api/stats/top-mover",
        &[("authorization", "Bearer tok-stats-rich"), ("if-none-match", etag.as_str())],
    ).await;
    assert_eq!(s3, StatusCode::NOT_MODIFIED);
    assert!(b3.is_empty(), "304 carries no body");
    assert_eq!(h3[header::ETAG], etag.as_str());
    assert_eq!(h3["x-stats-cache"], "hit", "Node stamps the header before the freshness check");

    let (s4, _, _) = request(
        &r, "GET", "/api/stats/history",
        &[("authorization", "Bearer tok-stats-rich"), ("if-none-match", "*")],
    ).await;
    assert_eq!(s4, StatusCode::NOT_MODIFIED, "'*' always matches (etag_matches)");

    // Second user: own key, own miss.
    let (s5, h5, _) = request(&r, "GET", "/api/stats/top-mover", &auth2()).await;
    assert_eq!(s5, StatusCode::OK);
    assert_eq!(h5["x-stats-cache"], "miss", "per-user cache keys");
}

