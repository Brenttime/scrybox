#[tokio::test]
async fn proxied_write_bumps_only_that_users_generation() {
    let dir = tempfile::tempdir().unwrap();
    let db_path = seeded_stats_db(dir.path(), "gen.db");
    let upstream = spawn_fake_node().await;
    let r = router_for(db_path, &["stats_subs"], &format!("http://{upstream}"));

    // Warm both users' top-mover entries.
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(h["x-stats-cache"], "miss");
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(h["x-stats-cache"], "hit");
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth2()).await;
    assert_eq!(h["x-stats-cache"], "miss");
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth2()).await;
    assert_eq!(h["x-stats-cache"], "hit");

    // Authenticated non-GET /api write, proxied → invalidateOnWrite twin.
    let (s, h, _) = request(&r, "POST", "/api/collection", &auth()).await;
    assert_eq!(s, StatusCode::OK);
    assert_eq!(h["x-node"], "1", "write rides the proxy (group off)");
    tokio::time::sleep(std::time::Duration::from_millis(100)).await;

    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(h["x-stats-cache"], "miss", "proxied write must bump the writer's generation");
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth2()).await;
    assert_eq!(h["x-stats-cache"], "hit", "gen is per-user (bump(req.user.id)), not global");

    // HEAD and unauthenticated writes never bump.
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(h["x-stats-cache"], "hit");
    let _ = request(&r, "POST", "/api/collection", &[("authorization", "Bearer bogus")]).await;
    let _ = request(&r, "HEAD", "/api/collection", &auth()).await;
    tokio::time::sleep(std::time::Duration::from_millis(100)).await;
    let (_, h, _) = request(&r, "GET", "/api/stats/top-mover", &auth()).await;
    assert_eq!(h["x-stats-cache"], "hit", "unauth/HEAD writes never bump");
}

