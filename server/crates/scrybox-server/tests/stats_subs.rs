#[tokio::test]
async fn history_period_counts_and_label_style() {
    let dir = tempfile::tempdir().unwrap();
    let upstream = spawn_fake_node().await;
    let r = router_for(seeded_stats_db(dir.path(), "hist.db"), &["stats_subs"], &format!("http://{upstream}"));

    // Node's toLocaleDateString styles: 7d→weekday, 30d→"D/MM" (month NOT
    // zero-padded), 1y→"MMM YY", 5y→"MMM YYYY".
    let month_names = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
    let label_ok = |s: &str, style: usize| -> bool {
        match style {
            0 => ["Mon","Tue","Wed","Thu","Fri","Sat","Sun"].contains(&s),
            1 => {
                let mut it = s.split(' ');
                let (mo, d) = (it.next().unwrap_or(""), it.next().unwrap_or(""));
                it.next().is_none() && month_names.contains(&mo)
                    && !d.is_empty() && d.len() <= 2 && d.bytes().all(|b| b.is_ascii_digit())
            }
            2 => {
                let mut it = s.split(' ');
                let (mo, y) = (it.next().unwrap_or(""), it.next().unwrap_or(""));
                it.next().is_none() && month_names.contains(&mo)
                    && y.len() == 2 && y.bytes().all(|b| b.is_ascii_digit())
            }
            _ => {
                let mut it = s.split(' ');
                let (mo, y) = (it.next().unwrap_or(""), it.next().unwrap_or(""));
                it.next().is_none() && month_names.contains(&mo)
                    && y.len() == 4 && y.bytes().all(|b| b.is_ascii_digit())
            }
        }
    };
    let cases = [
        ("period=7d", 7usize, 0usize),
        ("period=30d", 30, 1),
        ("", 30, 1),                 // missing → 30d
        ("period=", 30, 1),          // empty string is falsy → '30d'
        ("period=xyz", 30, 1),       // unknown falls to the 30 branch
        ("period=7d&period=1y", 30, 1), // qs array join '7d,1y' → not the 7d branch
        ("period[]=7d", 7, 0),       // qs 'String(array)=[7d]' → name '7d' — SAME
                                     // cache name as the warm ?period=7d entry, so
                                     // it's served the weekday body (aliasing Node
                                     // reproduces through cached(), seen above)
        ("period=1y", 12, 2),
        ("period=5y", 20, 3),
    ];
    for (q, want, style) in cases {
        let path = if q.is_empty() { "/api/stats/history".to_string() } else { format!("/api/stats/history?{q}") };
        let (s, _, v) = get_json(&r, &path).await;
        assert_eq!(s, StatusCode::OK, "{path}");
        let arr = v.as_array().unwrap_or_else(|| panic!("{path}: body not an array: {v}"));
        assert_eq!(arr.len(), want, "{path} target count");
        assert!(
            arr.iter().all(|e| label_ok(e["date"].as_str().unwrap_or(""), style) && e["value"].is_number()),
            "{path}: date/value shape wrong (style {style}): {arr:?}",
        );
    }

    // 7d labels: distinct targets never collide on a label (the sweep walks
    // one day per target, so seven consecutive days give seven labels —
    // month-boundary flips are allowed, duplicates are not).
    let (_, _, v) = get_json(&r, "/api/stats/history?period=7d").await;
    let arr = v.as_array().unwrap();
    let dates: Vec<&str> = arr.iter().map(|e| e["date"].as_str().unwrap()).collect();
    assert_eq!(dates.iter().collect::<std::collections::HashSet<_>>().len(), 7, "labels unique per target: {dates:?}");
}

