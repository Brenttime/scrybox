#[derive(Clone)]
enum Kind {
    History(Period),
    Networth,
    TopMover,
}

impl Kind {
    fn cache_name(&self) -> String {
        match self {
            Kind::History(p) => format!("history:{}", p.name),
            Kind::Networth => "networth".into(),
            Kind::TopMover => "top-mover".into(),
        }
    }
    fn err_msg(&self) -> &'static str {
        match self {
            Kind::History(_) => "Failed to compute timeline history",
            Kind::Networth => "Failed to compute net worth",
            Kind::TopMover => "Top mover unavailable",
        }
    }
    fn build(&self, pool: &DbPool, user_id: i64, hist_cache: bool) -> Result<Vec<u8>, String> {
        match self {
            Kind::History(p) => build_history_body(pool, user_id, p, hist_cache),
            Kind::Networth => build_networth_body(pool, user_id),
            Kind::TopMover => build_top_mover_body(pool, user_id),
        }
    }
}

pub async fn handle_history(method: Method, State(st): State<AppState>, req: Request) -> Response {
    route("history", "GET /api/stats/history", method, st, req, |req| {
        Kind::History(resolve_period(req.uri().query()))
    })
    .await
}

pub async fn handle_networth(method: Method, State(st): State<AppState>, req: Request) -> Response {
    route("networth", "GET /api/stats/networth", method, st, req, |_| Kind::Networth).await
}

pub async fn handle_top_mover(method: Method, State(st): State<AppState>, req: Request) -> Response {
    route("top-mover", "GET /api/stats/top-mover", method, st, req, |_| Kind::TopMover).await
}

async fn proxy_fallback(st: &AppState, req: Request) -> Response {
    // Same policy as the /stats mount: HEAD, unknown methods and any path the
    // mount caught that Express would answer elsewhere go to Node untouched.
    crate::proxy(State(st.clone()), req).await
}

async fn route(
    _tag: &str,
    route_name: &str,
    method: Method,
    st: AppState,
    req: Request,
    kind_fn: impl FnOnce(&Request) -> Kind,
) -> Response {
    // route_name is the exact public path prefixed with "GET " (e.g.
    // "GET /api/stats/history"); strip the verb to get the match target.
    let expected = &route_name["GET ".len()..];
    if method != Method::GET
        || req.uri().path() != expected
        || !st.owns("stats_subs")
        || st.db.is_none()
    {
        return proxy_fallback(&st, req).await;
    }
    let kind = kind_fn(&req);
    let pool = st.db.clone().unwrap();
    let headers = req.headers().clone();

    // authenticateToken (Bearer session; API keys GET-only) — same 401/403
    // bodies as the /stats port.
    let token = crate::auth::bearer_token(&headers).map(str::to_string);
    let user = match crate::auth::authenticate(&pool, token.as_deref(), true) {
        Ok(u) => u,
        Err(res) => return res,
    };
    let user_id = user.id;
    let inm = headers.get("if-none-match").and_then(|v| v.to_str().ok()).map(str::to_string);
    let ae = headers.get(header::ACCEPT_ENCODING).and_then(|v| v.to_str().ok()).map(str::to_string);

    let cache = Arc::clone(&st.stats_cache);
    let (resp_cache, hist_cache) = cache_flags();

    let outcome: Result<(bool, Arc<StatsEntry>), String> = if resp_cache {
        // Phase 1: resolve the shared-store key (gen, rev) and probe —
        // statsCache.js reads dataRevision per request, even for hits.
        let key = {
            let conn = match pool.get() {
                Ok(c) => c,
                Err(e) => return server_error(500, kind.err_msg(), true, Some(&format!("read pool: {e}"))),
            };
            let gen = cache.gen_of(user_id);
            let rev = StatsCache::revision_of(&conn);
            StatsCache::key_named(user_id, gen, rev.as_deref(), &kind.cache_name())
        };
        if let Some(entry) = cache.get_entry(&key) {
            Ok((true, entry))
        } else {
            // Phase 2: coalesced regeneration (same single-flight shape as
            // /stats; Node runs concurrent misses redundantly, the shared
            // body is identical either way). No SWR: Node's cached() has no
            // stale fallback for these names — a cold entry blocks and
            // computes.
            let slot = cache.slot_for(&key);
            let init_cache = Arc::clone(&cache);
            let init_pool = Arc::clone(&pool);
            let init_key = key.clone();
            let init_kind = kind.clone();
            let init = move || async move {
                let c = Arc::clone(&init_cache);
                let p = Arc::clone(&init_pool);
                let k = init_key.clone();
                let r = tokio::task::spawn_blocking(move || -> Result<Arc<StatsEntry>, String> {
                    let raw = init_kind.build(&p, user_id, hist_cache)?;
                    let entry = Arc::new(StatsEntry::new(Bytes::from(raw)));
                    c.set_named(user_id, k, Arc::clone(&entry));
                    Ok(entry)
                })
                .await
                .map_err(|e| format!("stats task panicked: {e}"))?;
                Ok(r)
            };
            let res: Result<&Result<Arc<StatsEntry>, String>, String> = slot.get_or_try_init(init).await;
            cache.finish_key(&key);
            match res {
                Ok(Ok(e)) => Ok((false, e.clone())),
                Ok(Err(e)) => Err(e.clone()),
                Err(e) => Err(e),
            }
        }
    } else {
        let build_pool = Arc::clone(&pool);
        let build_kind = kind.clone();
        match tokio::task::spawn_blocking(move || -> Result<(bool, Arc<StatsEntry>), String> {
            let raw = build_kind.build(&build_pool, user_id, hist_cache)?;
            Ok((false, Arc::new(StatsEntry::new(Bytes::from(raw)))))
        })
        .await
        {
            Ok(r) => r,
            Err(e) => {
                return server_error(500, kind.err_msg(), true, Some(&format!("stats task panicked: {e}")))
            }
        }
    };

    let (hit, mut entry) = match outcome {
        Ok(v) => v,
        Err(e) => return server_error(500, kind.err_msg(), resp_cache, Some(&e)),
    };

    // networth's onHit: fresh asOf on cache hits only (the miss response and
    // the stored body carry the compute-time asOf, like Node's wrapper).
    if hit && matches!(kind, Kind::Networth) {
        match refresh_asof(entry.raw(), crate::stats::now_ms()) {
            Ok(fresh) => entry = Arc::new(StatsEntry::new(Bytes::from(fresh))),
            Err(e) => return server_error(500, kind.err_msg(), resp_cache, Some(&e)),
        }
    }

    // When Node's wrapper is disabled (NODE_ENV=test / STATS_CACHE=0) it
    // calls the handler directly — res.json is never wrapped, so the
    // response carries NO X-Stats-Cache header at all. Match that.
    let cache_header: Option<HeaderValue> =
        resp_cache.then(|| HeaderValue::from_static(if hit { "hit" } else { "miss" }));

    if let Some(tag) = inm.as_deref() {
        if etag_matches(Some(tag), entry.etag()) {
            let mut resp = Response::builder()
                .status(StatusCode::NOT_MODIFIED)
                .header(header::ETAG, entry.etag());
            if let Some(h) = cache_header.clone() {
                resp = resp.header("x-stats-cache", h);
            }
            return resp.body(Body::empty()).unwrap();
        }
    }

    let raw_len = entry.raw().len();
    let use_gzip = wants_encoding(ae.as_deref(), "gzip", raw_len) && entry.gz().is_some();
    let body_bytes: Bytes = if use_gzip { entry.gz().clone().unwrap() } else { entry.raw().clone() };

    let mut resp = Response::builder()
        .status(StatusCode::OK)
        .header(header::CONTENT_TYPE, "application/json; charset=utf-8")
        .header(header::ETAG, entry.etag());
    if let Some(h) = cache_header {
        resp = resp.header("x-stats-cache", h);
    }
    if use_gzip {
        resp = resp.header(header::CONTENT_ENCODING, "gzip").header(header::VARY, "Accept-Encoding");
    }
    resp.body(Body::from(body_bytes)).unwrap()
}

/// stats.js catch shape: console.error + res.status(500).json({error}). The
/// cached() wrapper still stamped X-Stats-Cache: miss on the way out (its
/// wrapped res.json runs, the >=400 guard only skips the STORE), so the 500
/// carries the header too.
fn server_error(_status: u16, msg: &str, miss: bool, detail: Option<&str>) -> Response {
    if let Some(d) = detail {
        tracing::error!(error = %d, "stats sub-route computation failed");
    }
    let mut resp = (
        StatusCode::INTERNAL_SERVER_ERROR,
        [(header::CONTENT_TYPE, "application/json; charset=utf-8")],
        axum::Json(serde_json::json!({ "error": msg })),
    )
        .into_response();
    if miss {
        resp.headers_mut().insert("x-stats-cache", HeaderValue::from_static("miss"));
    }
    resp
}

