struct Addition {
    time: f64,
    quantity: f64,
    current_value: f64,
}

struct HistCard {
    additions: Vec<Addition>,
    times: Vec<f64>,
    prices: Vec<f64>,
}

fn hist_store() -> &'static Mutex<HashMap<i64, (String, Arc<Vec<HistCard>>)>> {
    static STORE: OnceLock<Mutex<HashMap<i64, (String, Arc<Vec<HistCard>>)>>> = OnceLock::new();
    STORE.get_or_init(Default::default)
}

fn load_history_cards(pool: &DbPool, user_id: i64) -> Result<Vec<HistCard>, String> {
    let conn = pool.get().map_err(|e| format!("read pool: {e}"))?;
    let mut stmt = conn.prepare(HISTORY_CARDS_SQL).map_err(|e| format!("prepare: {e}"))?;
    let mut rows = stmt
        .query_map([user_id], |row| {
            Ok((row.get::<_, Option<String>>(1)?, row.get::<_, Option<String>>(2)?))
        })
        .map_err(|e| format!("query: {e}"))?;
    let mut cards = Vec::new();
    while let Some((additions, history)) = rows.next().transpose().map_err(|e| format!("row: {e}"))? {
        let card = decode_hist_card(additions.as_deref(), history.as_deref())?;
        cards.push(card);
    }
    Ok(cards)
}

/// JS destructuring + parse rules for one historyCards row. A non-array
/// element throws in Node (destructuring a non-iterable) — mirrored as Err,
/// which the handler answers 500, same as stats.js's catch.
fn decode_hist_card(additions: Option<&str>, history: Option<&str>) -> Result<HistCard, String> {
    use crate::stats::parse_sqlite_utc;

    let parsed: Vec<Value> = serde_json::from_str(additions.filter(|s| !s.is_empty()).unwrap_or("[]"))
        .map_err(|e| format!("additions json: {e}"))?;
    let mut adds = Vec::with_capacity(parsed.len());
    for el in parsed {
        let arr = el.as_array().ok_or("additions element is not an array")?;
        let get = |i: usize| arr.get(i).cloned().unwrap_or(Value::Null);
        // const time = parseSqliteUtc(added_at).getTime(); if (!isFinite) drop.
        let Some(time) = get(1).as_str().and_then(parse_sqlite_utc) else { continue };
        let quantity = js_to_num(&get(0));
        let price = js_to_num(&crate::collection::resolve_card_price(
            &get(3),
            &get(2),
            &get(4),
            &get(5),
            &get(6),
        ));
        adds.push(Addition { time, quantity, current_value: quantity * price });
    }
    // .sort((a, b) => a.time - b.time) — stable, time already finite.
    adds.sort_by(|a, b| a.time.partial_cmp(&b.time).unwrap_or(std::cmp::Ordering::Equal));

    let parsed: Vec<Value> = serde_json::from_str(history.filter(|s| !s.is_empty()).unwrap_or("[]"))
        .map_err(|e| format!("history json: {e}"))?;
    let mut hist: Vec<(String, f64, f64)> = Vec::with_capacity(parsed.len());
    for el in parsed {
        let arr = el.as_array().ok_or("history element is not an array")?;
        let price = arr.get(0).cloned().unwrap_or(Value::Null);
        let ra = arr.get(1).cloned().unwrap_or(Value::Null);
        let ra_str = match &ra {
            Value::String(s) => s.clone(),
            other => other.to_string(), // JS comparator coerces; recorded_at is TEXT NOT NULL in practice
        };
        let time = crate::stats::parse_sqlite_utc(&ra_str).unwrap_or(f64::NAN);
        hist.push((ra_str, js_to_num(&price), time));
    }
    // .sort((a, b) => a.recordedAt < b.recordedAt ? -1 : ... > ... ? 1 : 0) —
    // stable string comparator.
    hist.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(HistCard {
        additions: adds,
        times: hist.iter().map(|(_, _, t)| *t).collect(),
        prices: hist.iter().map(|(_, p, _)| *p).collect(),
    })
}

fn history_cards(
    pool: &DbPool,
    user_id: i64,
    allow_cache: bool,
) -> Result<Arc<Vec<HistCard>>, String> {
    let rev = StatsCache::revision(pool);
    if allow_cache {
        if let (Some(rev), Some(hit)) = (rev.as_ref(), hist_store().lock().unwrap().get(&user_id)) {
            if &hit.0 == rev {
                return Ok(Arc::clone(&hit.1));
            }
        }
    }
    let cards = Arc::new(load_history_cards(pool, user_id)?);
    // Node only stores when nothing moved while loading (a racing write must
    // not pin pre-write rows under the post-write revision).
    if allow_cache {
        if let (Some(rev), Some(after)) = (rev.as_ref(), StatsCache::revision(pool)) {
            if after == *rev {
                hist_store().lock().unwrap().insert(user_id, (rev.clone(), Arc::clone(&cards)));
            }
        }
    }
    Ok(cards)
}

