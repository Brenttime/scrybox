const DAY_MS: i64 = 24 * 60 * 60 * 1000;
const MONTHS: [&str; 12] = [
    "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
];
// JS weekday short form, index 0 = Sunday. 1970-01-01 (day 0) was a Thursday.
const WEEKDAYS: [&str; 7] = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

// SQL copies must stay byte-identical to backend/src/routes/stats.js.
const HISTORY_CARDS_SQL: &str = r#"
    WITH cards AS MATERIALIZED (
      SELECT c.card_id,
             json_group_array(json_array(
               c.quantity, c.added_at, c.printing, COALESCE(c.is_proxy, 0),
               cc.price_trend, cc.price_normal, cc.price_holofoil
             )) AS additions
      FROM collection c
      JOIN card_cache cc ON cc.id = c.card_id
      WHERE c.user_id = ?
      GROUP BY c.card_id
    ),
    histories AS MATERIALIZED (
      SELECT ph.card_id,
             json_group_array(json_array(ph.price, ph.recorded_at)) AS history
      FROM cards c
      CROSS JOIN price_history ph
      WHERE ph.card_id = c.card_id
      GROUP BY ph.card_id
    )
    SELECT c.card_id, c.additions, COALESCE(h.history, '[]') AS history
    FROM cards c
    LEFT JOIN histories h ON h.card_id = c.card_id
  "#;

const NETWORTH_SQL: &str = r#"
      SELECT c.quantity, c.purchase_price, c.printing, c.is_proxy, cc.price_currency,
             cc.price_trend, cc.price_normal, cc.price_holofoil
      FROM collection c
      JOIN card_cache cc ON c.card_id = cc.id
      WHERE c.user_id = ?
    "#;

const TOP_MOVER_SQL: &str = r#"
      WITH o AS (
        SELECT card_id, MIN(id) AS entry_id
        FROM collection
        WHERE user_id = ? AND COALESCE(is_proxy, 0) = 0
        GROUP BY card_id
      ),
      p AS (
        SELECT o.card_id, o.entry_id,
               (SELECT price FROM price_history ph WHERE ph.card_id = o.card_id
                ORDER BY ph.recorded_at DESC LIMIT 1) AS cur,
               (SELECT price FROM price_history ph WHERE ph.card_id = o.card_id
                  AND ph.recorded_at <= datetime('now', '-24 hours')
                ORDER BY ph.recorded_at DESC LIMIT 1) AS prev
        FROM o
      )
      SELECT p.cur, p.prev, p.cur - p.prev AS gain,
             c.id AS entry_id, c.quantity, c.condition, c.printing, c.language, c.purchase_price, c.is_proxy,
             cc.id AS card_id, cc.name, cc.printed_name, cc.rarity, cc.set_name, cc.set_id, cc.number, cc.image_url,
             cc.supertype, cc.subtypes, cc.types, cc.cmc, cc.color_identity, cc.price_trend,
             cc.price_normal, cc.price_holofoil, cc.price_estimated
      FROM p
      JOIN collection c ON c.id = p.entry_id
      JOIN card_cache cc ON cc.id = p.card_id
      WHERE p.prev > 0 AND p.cur > p.prev
      ORDER BY gain DESC
      LIMIT 1
    "#;

