/// (response cache enabled, historyCards cache enabled). statsCache.js's
/// `disabled()` disables the response cache on NODE_ENV=test OR
/// STATS_CACHE=0; stats.js's historyCards only honours STATS_CACHE=0.
fn cache_flags() -> (bool, bool) {
    static FLAGS: OnceLock<(bool, bool)> = OnceLock::new();
    *FLAGS.get_or_init(|| {
        let zero = std::env::var("STATS_CACHE").ok().as_deref() == Some("0");
        let test = std::env::var("NODE_ENV").ok().as_deref() == Some("test");
        (!test && !zero, !zero)
    })
}

// ---------------------------------------------------------------------------
// period (express qs + `String(period || '30d')` semantics)
// ---------------------------------------------------------------------------

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Style {
    Weekday,
    MonthDay,
    Month2Y,
    MonthYear,
}

#[derive(Clone, Debug)]
pub struct Period {
    /// The `history:${String(req.query.period || '30d')}` cache name (stored
    /// without the `history:` prefix).
    name: String,
    /// Which branch the HANDLER takes: `period === '7d'` etc. — strict
    /// equality against the raw query value, so an array that stringifies to
    /// '7d' (?period[]=7d) falls through to the 30d branch exactly like Node.
    style: Style,
}

fn push_idx(items: &mut Vec<Option<String>>, i: usize, v: String) {
    while items.len() <= i {
        items.push(None);
    }
    items[i] = Some(v);
}

/// Mirror of express's qs-parsed `req.query.period` → cache-name string and
/// handler style. Verified against `qs.parse` inside the test container:
///   period=7d                 → '7d'          (string; style Weekday)
///   period=                   → '30d'         ('' falsy)
///   period=a&period=b         → 'a,b'         (array join)
///   period[]=a                → 'a'           (array join; style stays 30d)
///   period[1]=b&period[0]=a   → 'a,b'         (indexed, sparse)
///   period[foo]=1             → '[object Object]'
///   (absent)                  → '30d'
fn resolve_period(query: Option<&str>) -> Period {
    let q = query.unwrap_or("");
    let mut plain: Vec<String> = Vec::new();
    let mut items: Vec<Option<String>> = Vec::new();
    let mut bracket = false;
    let mut obj = false;
    let mut seen = false;
    for (k, v) in form_urlencoded::parse(q.as_bytes()) {
        if k == "period" {
            seen = true;
            let v = v.into_owned();
            plain.push(v.clone());
            items.push(Some(v));
        } else if k == "period[]" {
            seen = true;
            bracket = true;
            items.push(Some(v.into_owned()));
        } else if let Some(inner) = k.strip_prefix("period[").and_then(|s| s.strip_suffix(']')) {
            seen = true;
            bracket = true;
            match inner.parse::<usize>() {
                Ok(i) => push_idx(&mut items, i, v.into_owned()),
                Err(_) => obj = true,
            }
        }
    }
    if !seen {
        return Period { name: "30d".into(), style: Style::MonthDay };
    }
    if obj {
        return Period { name: "[object Object]".into(), style: Style::MonthDay };
    }
    if bracket || plain.len() >= 2 {
        // Array value: String(array) = comma-join, holes stringify to ''.
        // A non-empty array is ALWAYS truthy in JS (even ['']), so no
        // '30d' fallback here — that only applies to undefined/''.
        let name = items
            .iter()
            .map(|v| v.as_deref().unwrap_or(""))
            .collect::<Vec<_>>()
            .join(",");
        return Period { name, style: Style::MonthDay };
    }
    // Exactly one plain occurrence → string value.
    let v = plain.into_iter().next().unwrap_or_default();
    if v.is_empty() {
        return Period { name: "30d".into(), style: Style::MonthDay };
    }
    let style = match v.as_str() {
        "7d" => Style::Weekday,
        "1y" => Style::Month2Y,
        "5y" => Style::MonthYear,
        _ => Style::MonthDay, // '30d' and every unknown value share the else branch
    };
    Period { name: v, style }
}

// ---------------------------------------------------------------------------
// UTC date labels (toLocaleDateString, en-US, TZ=UTC like the Node container)
// ---------------------------------------------------------------------------

/// Howard Hinnant's civil_from_days: days since 1970-01-01 → (year, month, day).
fn civil_from_days(z0: i64) -> (i64, u32, u32) {
    let z = z0 + 719468;
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = (z - era * 146097) as u64; // [0, 146096]
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365; // [0, 399]
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // [0, 365]
    let mp = (5 * doy + 2) / 153; // [0, 11]
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32; // [1, 31]
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

fn label(style: Style, target_ms: i64) -> String {
    let days = target_ms.div_euclid(DAY_MS);
    let (y, m, d) = civil_from_days(days);
    match style {
        Style::Weekday => WEEKDAYS[(days + 4).rem_euclid(7) as usize].to_string(),
        Style::MonthDay => format!("{} {}", MONTHS[(m - 1) as usize], d),
        Style::Month2Y => format!("{} {:02}", MONTHS[(m - 1) as usize], y.rem_euclid(100)),
        Style::MonthYear => format!("{} {}", MONTHS[(m - 1) as usize], y),
    }
}

/// (count, step_ms) per period branch — stats.js targets.
fn plan(style: Style) -> (usize, i64) {
    match style {
        Style::Weekday => (7, DAY_MS),
        Style::Month2Y => (12, 30 * DAY_MS),
        Style::MonthYear => (20, 91 * DAY_MS),
        Style::MonthDay => (30, DAY_MS),
    }
}

