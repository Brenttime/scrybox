//! Port of the three remaining `cached()` GET sub-routes of
//! `backend/src/routes/stats.js`: `/stats/history`, `/stats/networth` and
//! `/stats/top-mover` (route group `stats_subs`). `/stats/commander-of-the-day`
//! stays on Node — it fetches through `scryfallApi.fetchWindow`, which is
//! Lane B surface, and forwarding it whole-request would not make it native
//! (Lane A ruling, iter 24).
//!
//! Parity contract (BRIEF rule 1): byte-identical body for the same DB state
//! (Express default ETag + If-None-Match replay), identical X-Stats-Cache
//! hit/miss, identical cache invalidation (same shared gen/rev key shape as
//! the `/stats` port — one Map across all names, per utils/statsCache.js).
//! Every JS numeric step is reproduced with JS semantics via the stats.rs
//! helpers (toFixed→parseFloat, Math.round, Number() coercion, integral-float
//! serialization). Date labels: `toLocaleDateString()` runs in the Node
//! container's UTC/en-US (TZ unset), so the label formatters here are fixed
//! UTC + en-US short forms, independent of the Rust host's TZ — vectors in
//! tests were generated by `node` inside the test container.

