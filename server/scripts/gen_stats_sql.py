#!/usr/bin/env python3
"""Generate crates/scrybox-server/src/stats_sql.rs from the Node sources.

The /stats SQL must be a VERBATIM copy of the template literals in
backend/src/routes/stats.js and of deckOwnership.js's OWNERSHIP_SQL (with
cardIdentity's helper expressions expanded exactly as they emit). Transcribing
by hand invites drift, so the strings are extracted from the source files.

Regenerate after any change to those Node files:
    python3 scripts/gen_stats_sql.py
"""
import re
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent  # wt/server
BACKEND = ROOT.parent / "backend" / "src"

stats_js = (BACKEND / "routes" / "stats.js").read_text()
ownership_js = (BACKEND / "utils" / "deckOwnership.js").read_text()

tpls = re.findall(r"`([^`]*)`", stats_js)


def pick(pred, name):
    cands = [t for t in tpls if all(p in t for p in pred)]
    if len(cands) != 1:
        raise SystemExit(f"expected exactly one template for {name}, got {len(cands)}")
    t = cands[0]
    if "${" in t:
        raise SystemExit(f"template {name} contains interpolation; refusing to port")
    return t


AGGREGATE = pick(["AS total_cards", "color_values", "change_prices"], "AGGREGATE_SQL")
TOP_VALUABLE = pick(["AS entry_id", "c.purchase_price", "LIMIT 6"], "TOP_VALUABLE")
RECENT_ADDED = pick(["AS entry_id", "c.added_at", "LIMIT 6"], "RECENT_ADDED")
DECK_ROWS = pick(["checked_out FROM decks"], "DECK_ROWS")

m = re.search(r"const OWNERSHIP_SQL = `([^`]*)`", ownership_js)
if not m:
    raise SystemExit("OWNERSHIP_SQL not found")
OWNERSHIP = m.group(1)

# cardIdentity.js expansions, copied from its template strings verbatim.
CARD_KEY_CC = "LOWER(TRIM(COALESCE(cc.name, '')))"
SUBTYPES_CC = "LOWER(COALESCE(cc.subtypes, ''))"
IS_LAND = f"(LOWER(COALESCE(cc.supertype, '')) = 'land' OR INSTR({SUBTYPES_CC}, '\"land\"') > 0)"
IS_BASIC_TYPE = (
    f"({CARD_KEY_CC} IN ('plains', 'island', 'swamp', 'mountain', 'forest', 'wastes') "
    f"OR INSTR({SUBTYPES_CC}, '\"basic\"') > 0)"
)
IS_BASIC_LAND_CC = f"({IS_LAND} AND {IS_BASIC_TYPE})"

OWNERSHIP = OWNERSHIP.replace("${sqlCardKey('cc')}", CARD_KEY_CC)
OWNERSHIP = OWNERSHIP.replace("${sqlIsBasicLand('cc')}", IS_BASIC_LAND_CC)
# owned CTE keys the collection side off card_cache alias occ.
OWNERSHIP = OWNERSHIP.replace("${sqlCardKey('occ')}", "LOWER(TRIM(COALESCE(occ.name, '')))")
if "${" in OWNERSHIP:
    leftover = re.findall(r"\$\{[^}]*\}", OWNERSHIP)
    raise SystemExit(f"unexpanded interpolation left in OWNERSHIP_SQL: {leftover}")


def rust_str(s: str) -> str:
    """Raw string with the smallest hash run that cannot terminate early."""
    hashes = 0
    while f'"{"#" * hashes}' in s:
        hashes += 1
    h = "#" * hashes
    return f'r{h}"{s}"{h}'


HEADER = """//! GENERATED by server/scripts/gen_stats_sql.py — DO NOT EDIT.
//!
//! Verbatim SQL template copies from backend/src/routes/stats.js and
//! backend/src/utils/deckOwnership.js (cardIdentity expressions expanded as
//! they emit). Parity (BRIEF rule 1) depends on these strings staying
//! byte-identical to the Node sources; regenerate instead of hand-editing.

/// AGGREGATE_SQL from stats.js (the single dashboard aggregate).
"""

out = HEADER
out += f"pub(crate) const AGGREGATE_SQL: &str = {rust_str(AGGREGATE)};\n\n"
out += "/// topValuableQuery from stats.js.\n"
out += f"pub(crate) const TOP_VALUABLE_SQL: &str = {rust_str(TOP_VALUABLE)};\n\n"
out += "/// recentRows query from stats.js.\n"
out += f"pub(crate) const RECENT_ADDED_SQL: &str = {rust_str(RECENT_ADDED)};\n\n"
out += "/// Deck tile rows from stats.js.\n"
out += f"pub(crate) const DECK_ROWS_SQL: &str = {rust_str(DECK_ROWS)};\n\n"
out += "/// OWNERSHIP_SQL from utils/deckOwnership.js.\n"
out += f"pub(crate) const OWNERSHIP_SQL: &str = {rust_str(OWNERSHIP)};\n"

dest = ROOT / "crates" / "scrybox-server" / "src" / "stats_sql.rs"
dest.write_text(out)
print(f"wrote {dest} ({len(out)} bytes)")
