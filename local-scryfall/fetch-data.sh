#!/usr/bin/env bash
# Fetch Scryfall bulk data into $SCRYFALL_DATA_DIR (default ./data) if missing.
# Network-tolerant by design: every failure warns and continues, so the
# container can boot against a pre-seeded volume with no egress at all.
#
# The download URLs are NOT stable — Scryfall versions every bulk file
# (…-YYYYMMDDHHMMSS.jsonl.gz). We resolve the live jsonl_download_uri from
# api.scryfall.com/bulk-data per file and fall back to URLs pinned from a real
# /bulk-data lookup on 2026-10-24 when that metadata call itself fails.
set -u

DATA_DIR="${SCRYFALL_DATA_DIR:-./data}"
mkdir -p "$DATA_DIR"

UA="curl/8.5.0"
BULK_META="https://api.scryfall.com/bulk-data"

PINNED_default_cards="https://data.scryfall.io/default-cards/default-cards-20261024090552.jsonl.gz"
PINNED_oracle_tags="https://data.scryfall.io/oracle-tags/oracle-tags-20261024090035.jsonl.gz"

# bulk_type -> local filename. Keys match /bulk-data/{type} endpoints.
fetch_bulk() {
  local type="$1" out="$2"
  local dest="$DATA_DIR/$out"
  if [ -s "$dest" ]; then
    echo "fetch-data: $out already present ($(stat -c%s "$dest" 2>/dev/null || echo ?) bytes), skipping"
    return 0
  fi
  # Resolve the live URL; the API field is jsonl_download_uri (the plain
  # download_uri is pretty-printed JSON — 4x the size, useless to us).
  local url
  url=$(curl -fsS --max-time 30 -H "User-Agent: $UA" -H "Accept: */*" \
        "$BULK_META/$type" 2>/dev/null \
        | python3 -c 'import json,sys; print(json.load(sys.stdin)["jsonl_download_uri"])' 2>/dev/null)
  if [ -z "$url" ]; then
    url="$(eval echo \$PINNED_$type)"
    echo "fetch-data: $type: could not resolve live URL, using pinned $url"
  fi
  echo "fetch-data: downloading $out from $url"
  # .part + atomic mv so a killed download never looks like a complete file
  # (the server would happily load a truncated gzip and panic mid-startup).
  if curl -fS --max-time 3600 -o "$dest.part" "$url"; then
    mv "$dest.part" "$dest"
    echo "fetch-data: $out OK"
  else
    rm -f "$dest.part"
    echo "fetch-data: WARN $out download failed — continuing; search runs without it (otag:/cards need it)" >&2
  fi
}

fetch_bulk default_cards default-cards.jsonl.gz
fetch_bulk oracle_tags  oracle-tags.jsonl.gz

# sets-meta.json is generated by data/gen_sets_meta.py from a /sets dump; the
# container builds it from a fresh /sets pull (same source, same shape) into
# $DATA_DIR. The image also ships the vendored data/ copies, so this whole
# block is optional freshness, never a boot requirement.
if [ ! -s "$DATA_DIR/sets-meta.json" ]; then
  echo "fetch-data: fetching sets metadata"
  SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
  if curl -fsS --max-time 60 -H "User-Agent: $UA" -H "Accept: */*" \
       https://api.scryfall.com/sets -o "$DATA_DIR/scryfall-sets-raw.json"; then
    if command -v python3 >/dev/null 2>&1 && [ -f "$SCRIPT_DIR/data/gen_sets_meta.py" ]; then
      python3 "$SCRIPT_DIR/data/gen_sets_meta.py" "$DATA_DIR/scryfall-sets-raw.json" "$DATA_DIR" \
        || echo "fetch-data: WARN gen_sets_meta.py failed — falling back to vendored data/" >&2
    fi
    rm -f "$DATA_DIR/scryfall-sets-raw.json"
  else
    echo "fetch-data: WARN /sets fetch failed — using vendored data/" >&2
  fi
  # Belt and braces: fill any gap the generated files left with the vendored
  # copies (resolve_blocks_path needs blocks.json and sets-meta.json to exist
  # side by side, and land_cycles.json next to sets-meta for is:dual etc.).
  if [ ! -s "$DATA_DIR/sets-meta.json" ]; then
    cp -n "$SCRIPT_DIR/data/sets-meta.json" "$DATA_DIR/" 2>/dev/null
  fi
  cp -n "$SCRIPT_DIR/data/blocks.json" "$SCRIPT_DIR/data/land_cycles.json" "$DATA_DIR/" 2>/dev/null
fi

echo "fetch-data: done"
